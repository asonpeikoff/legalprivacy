"""Community contribution: middle-relay / bridge torrc generation.

Tor has no separate "DNS node" role: the only relays that resolve names for other people are EXIT relays. So there
are three modes here:

  * middle / bridge: NON-EXIT. They carry the network's traffic (including the DNS requests on their way to an
    exit) but never resolve a name or connect to the internet for anyone. ExitPolicy is pinned to 'reject *:*'.
  * dns ("DNS helper"): an exit relay that ONLY does DNS. Tor answers other people's name lookups (RESOLVE
    requests) from it, and its exit policy lets traffic out to nothing except port 53 of two public resolvers
    (Quad9), so it cannot be used to reach websites or anything else. The resolver is hardened (random letter
    case, hijack detection, no search domains). Because it allows no web ports, the Tor authorities will not give
    it the Exit flag, so far fewer clients choose it than a normal exit: the help is real but modest.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

TORRC_HEADER = """\
# torrc generated by legalPrivacy v2 'legalprivacy relay gen'
# Community contribution: {mode} relay. NOT an exit node — ExitPolicy is
# pinned to reject-all below and cannot be overridden by this tool.
"""

TORRC_HEADER_DNS = """\
# torrc generated by legalPrivacy 'legalprivacy relay gen'
# Community contribution: DNS helper. An exit relay that ONLY does DNS: its exit policy
# allows nothing except port 53 of two public resolvers, so it can not be used to reach
# websites. Nothing else can be exited and the policy below cannot be overridden by this tool.
"""

# The only places a DNS helper lets traffic out to (Quad9, which validates DNSSEC and keeps no logs).
DNS_HELPER_POLICY = ["ExitPolicy accept 9.9.9.9:53", "ExitPolicy accept 149.112.112.112:53", "ExitPolicy reject *:*"]


class RelayConfigError(ValueError):
    pass


@dataclass
class RelaySpec:
    mode: str = "middle"              # middle | bridge
    nickname: str = "legalprivacy"
    contact: str | None = None
    bandwidth_rate: str = "5Mbit"
    or_port: int = 9001
    dir_port: int = 9030
    socks_policy: str = "reject *:*"
    practice: bool = False            # True: ORPort on loopback only, nothing published (safe to try)
    private: bool = False             # bridge: don't tell the bridge authority, so only people you give the line to can use it

    def validate(self) -> None:
        if self.mode not in ("middle", "bridge", "dns"):
            raise RelayConfigError(
                f"relay mode '{self.mode}' is not supported — "
                "legalPrivacy runs middle relays, bridges, or a DNS-only helper, never a general exit")
        if not (1024 <= self.or_port <= 65535 and self.or_port != 9050):
            raise RelayConfigError("or_port must be a non-9050 port in 1024-65535")
        if not (0 <= self.dir_port <= 65535 and self.dir_port != 9050):
            raise RelayConfigError("dir_port must be 0 or a non-9050 port in 1-65535")
        if self.dir_port != 0 and self.dir_port == self.or_port:
            raise RelayConfigError("or_port and dir_port must not be identical")
        if not (1 <= len(self.nickname) <= 19):
            raise RelayConfigError("nickname must be 1-19 chars, letters/digits")
        if not (self.nickname.isascii() and all(c.isalnum() for c in self.nickname)):
            raise RelayConfigError("nickname must be alphanumeric")
        # these two are written into the torrc: no line breaks, so they can never add another setting
        if self.contact and any(c in self.contact for c in "\r\n\0"):
            raise RelayConfigError("contact must be a single line")
        if not re.fullmatch(r"[0-9]+(?:\.[0-9]+)? ?[A-Za-z]*", self.bandwidth_rate or ""):
            raise RelayConfigError("bandwidth must look like 5Mbit or 500KBytes")


def _safe_path(path: str) -> str:
    if any(c in path for c in "\r\n\0\""):
        raise RelayConfigError("data directory path must be a single line without quotes")
    return path.replace("\\", "/")


def generate_torrc(spec: RelaySpec, data_dir: str | None = None) -> str:
    """Emit a non-exit relay torrc. Bridges get bridge-specific lines.

    data_dir (optional) adds a DataDirectory and logging to stdout, for a relay the app runs itself.
    spec.practice binds the ORPort to loopback and publishes nothing."""
    spec.validate()
    dns = spec.mode == "dns"
    lines = [
        (TORRC_HEADER_DNS if dns else TORRC_HEADER.format(mode=spec.mode)).rstrip(),
        "",
        f"Nickname {spec.nickname}",
    ]
    if spec.contact:
        lines.append(f"ContactInfo {spec.contact}")
    dir_port_line = "DirPort 0" if spec.mode == "bridge" else f"DirPort {spec.dir_port}"
    if spec.practice:
        dir_port_line = "DirPort 0"
    lines += [
        f"RelayBandwidthRate {spec.bandwidth_rate}",
        f"RelayBandwidthBurst {spec.bandwidth_rate}",
        f"ORPort 127.0.0.1:{spec.or_port}" if spec.practice else f"ORPort {spec.or_port}",
        dir_port_line,
        "SocksPort 0",
    ]
    if dns:
        lines += ["ExitRelay 1", "IPv6Exit 0", *DNS_HELPER_POLICY, "ExitPolicyRejectPrivate 1",
                  "ServerDNSRandomizeCase 1", "ServerDNSDetectHijacking 1", "ServerDNSSearchDomains 0",
                  "ServerDNSAllowBrokenConfig 0"]
    else:
        lines += ["ExitRelay 0", "ExitPolicy reject *:*"]
    lines.append(f"SocksPolicy {spec.socks_policy}")
    if data_dir:
        lines += [f'DataDirectory "{_safe_path(data_dir)}"', "Log notice stdout"]
    if spec.practice:
        lines += ["", "# Practice mode: loopback only, nothing is published, no one can connect"]
    else:
        lines += ["", "# Safety: publish reachable relay", "AssumeReachable 0"]
    if spec.mode == "bridge":
        lines += ["", "# Bridge mode: no descriptor publication to the main directory", "BridgeRelay 1"]
        lines.append("PublishServerDescriptor 0" if (spec.practice or spec.private) else "PublishServerDescriptor bridge")
    else:
        lines += ["", "BridgeRelay 0"]
        if spec.practice:
            lines.append("PublishServerDescriptor 0")
    # final guard: nothing may enable exiting after our policy line
    if not dns:
        lines += ["", "# pinned: this relay exits nothing", "ExitPolicy reject6 *:*"]
    else:
        lines += ["", "# pinned: the only exit is DNS to the two resolvers above", "ExitPolicy reject6 *:*"]
    return "\n".join(lines) + "\n"


