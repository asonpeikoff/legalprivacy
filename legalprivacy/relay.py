def generate_client_torrc(socks_port: int = 9050, control_port: int = 9051,
                          bridge_type: str = "snowflake",
                          custom_bridges: list[str] | None = None) -> str:
    """Generate a client-side torrc with bridge circumvention configured."""
    lines = [
        "# torrc generated by legalPrivacy v2 'legalprivacy relay gen-client'",
        "# Client mode with bridge censorship circumvention",
        "",
        f"SocksPort 127.0.0.1:{socks_port}",
        f"ControlPort 127.0.0.1:{control_port}",
        "CookieAuthentication 1",
        "",
        "# Enable bridges",
        "UseBridges 1",
    ]
    if bridge_type == "snowflake":
        lines += [
            "ClientTransportPlugin snowflake exec /usr/bin/snowflake-client",
            *(custom_bridges or DEFAULT_SNOWFLAKE_BRIDGES),
        ]
    elif bridge_type == "obfs4":
        lines += [
            "ClientTransportPlugin obfs4 exec /usr/bin/obfs4proxy",
            *(custom_bridges or DEFAULT_OBFS4_BRIDGES),
        ]
    elif custom_bridges:
        lines += custom_bridges
    return "\n".join(lines) + "\n"


def warn_if_exit_requested(torrc_text: str) -> list[str]:
    """Defensive: scan a generated torrc for any exit capability.

    Only reject-all policies (v4 and v6) are acceptable on any ExitPolicy line.
    """
    def is_reject_all(line: str) -> bool:
        line = line.lower().replace("reject6", "reject")
        return "accept" not in line and "reject *:*" in line

    warnings = []
    for line in torrc_text.splitlines():
        stripped = line.strip()
        if stripped.startswith("ExitPortObfuscation") or \
           (stripped.startswith("ExitPolicy") and not is_reject_all(stripped)):
            warnings.append(f"refusing exit capability in line: {stripped}")
    return warnings
